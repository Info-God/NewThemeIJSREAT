            <div class="doc">
                <h2 id="reviewer-editor" class="sec-anchor">Reviewer &amp; Editor AI Assistance</h2>
                <p>
                    Reviewers may wish to use Generative AI to improve the quality of the language in their review.
                    If they do so, they maintain responsibility for the content, accuracy and constructive feedback
                    within the review. Journal Editors maintain overall responsibility for the content published in
                    their journal and act as gatekeepers of the scholarly record. Editors may use Generative AI tools for assistance in looking for suitable peer-reviewers.
                </p>
                <p>
                    In rare circumstances, for example, if false or inaccurate data has been published and, if adopted, presents a serious health
                    risk, the original incorrect versions may be removed and a corrected version published. The reason for this partial removal
                    would be clearly stated in the most recent version.
                </p>
                <h4 id="limitations" class="sec-anchor">Generative AI Limitations</h4>
                <p>
                    Reviewers using ChatGPT or other Generative AI tools to generate review reports inappropriately will not
                    be invited to review for the journal and their review will not be included in the final decision.
                    Editors must not use ChatGPT or other Generative AI to generate decision letters,
                    or summaries of unpublished research.
                </p>
                <h4 id="undisclosed" class="sec-anchor">Undisclosed or Inappropriate use of Generative AI</h4>
                <p>
                    Reviewers suspecting the inappropriate or undisclosed use of generative AI in a submission should flag their concerns with the Journal Editor.
                    If Editors suspect the use of ChatGPT or any other generative AI in a submitted manuscript or a submitted review, they should consider this policy in undertaking an editorial assessment
                    of the matter or contact their FDRP representative for advice.
                    Fifth Dimension Research Publication and the Journal Editor will lead a joint investigation into concerns raised about the inappropriate or undisclosed use of Generative AI in a published article. The investigation will be undertaken in accordance with guidance issued by COPE and our internal policies.
                </p>

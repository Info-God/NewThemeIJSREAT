            <div>
                <h2 id="2-article-processing-charges-apcs" class="sec-anchor">
                    2. Article Processing Charges (APCs)
                </h2>
                <ul>
                    <li>APCs are non-refundable once the peer review process has begun.</li>
                    <li>If a manuscript is rejected before peer review, authors may request a full or partial refund (subject to administrative review).</li>
                    <li>Payments made in error (duplicate transactions, incorrect amounts) may be refunded upon verification.</li>
                </ul>
            </div>
            <div>
                <h2 id="3-fees-amp-payments" class="sec-anchor">
                    3. Fees &amp; Payments
                </h2>
                <p>
                    IJSREAT primarily follows an open-access model, but if any paid subscriptions/memberships are offered:
                </p>
                <ul>
                    <li>No refunds for digital access after content has been delivered.</li>
                    <li>Cancellations must be requested before the next billing cycle.</li>
                </ul>
            </div>
            <div>
                <h2 id="4-waivers-amp-financial-assistance" class="sec-anchor">
                    4. Waivers &amp; Financial Assistance
                </h2>
                <p>
